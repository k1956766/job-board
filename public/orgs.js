// 회사명 → (없으면) 제목으로 공공 연구기관 판별
export function researchGroupOf(company, title) {
  for (const text of [company, title]) {
    const hit = RESEARCH_INDEX.find((r) => r.test(text));
    if (hit) return hit.group;
  }
  return "";
}

