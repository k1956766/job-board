// ================================================================ 경력
// 반환: { min: 최소 경력 연수(없으면 null), newbie: 신입/무관 가능 여부(true/false/null) }
export function parseCareer(text) {
  const t = (text || "").replace(/\s+/g, " ");
  const newbie = /신입|경력\s*무관|경력무관|무관|인턴|체험형/.test(t) ? true : null;
  let min = null;
  // "경력 3년↑", "3년 이상", "3년이상 경력", "3~5년", "경력 2~5년", "5년+" (단, "4년↓"는 최대치라 제외)
  for (const m of t.matchAll(/(\d{1,2})\s*(?:~|-)\s*\d{1,2}\s*년|(\d{1,2})\s*년\s*(?:이상|↑|\+)|경력\s*(\d{1,2})\s*년(?!\s*(?:↓|이하|미만))/g)) {
    const v = +(m[1] || m[2] || m[3]);
    if (v > 0 && v < 40) min = min === null ? v : Math.min(min, v);
  }
  // 직급으로 드러나는 경력직 (연수 표기가 없을 때)
  if (min === null && !newbie && /(과장|차장|부장|팀장|실장|본부장|센터장|임원|대표이사|상임이사|비상임이사|책임연구원|수석연구원|책임급|수석급)/.test(t)) min = 5;
  return { min, newbie };
}

